public class Constructor_Vs_Function {
	
	
/* Constructor vs Function(Method)
 
Constructor : 
 		Name : same as class name
 		Call : when u create object
 		Return type : not applicable
 		Overloading: yes
 		Business logic : avoid
 		Purpose:
 			- initialize class variables using this keyword
 			- object restriction
		Store: Auxiliary space
		Main()/caller  : no main method in the same class where the constructor is also available

***********************************************************************************************

Function/Method : 
		Name : any name (avoid class name)
		Call : create object and use object reference
		Return type : may or may not return
		Overloading : Yes
		Business logic : Yes
		Purpose:
			- to define the business logic/feature
		Store : inside the object : one copy
		Main()/caller : use the main in different class (caller class) to call the function

 */
}
